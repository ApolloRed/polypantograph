"""
urdf_builder.py -- write a five-bar URDF from parameters given in code, when no
URDF is available.  It is the inverse of urdf_loader.py and produces exactly
the spanning-tree form that loader reads back: two serial 2R legs off a common
base, each ending in a fixed tip at the apex; the loop closure is supplied by
the model, not the file.

Typical use:

    from robotgeometry import FiveBarGeometry
    from dynamics import DynamicParameters
    from urdf_builder import write_urdf

    geom = FiveBarGeometry.symmetric(0.20, 0.25, 0.20)
    par  = DynamicParameters.uniform(geom, proximal_mass=0.5,
                                     distal_mass=0.3, apex_mass=0.10)
    write_urdf("my_robot.urdf", geom, par, name="my_robot")

or, for a symmetric robot straight from scalars (uniform slender rods):

    from urdf_builder import write_urdf_symmetric
    write_urdf_symmetric("my_robot.urdf", "my_robot",
                         a=0.20, b=0.25, d=0.20,
                         proximal_mass=0.5, distal_mass=0.3, apex_mass=0.10)

The file written round-trips through urdf_loader.load_urdf back to the same
geometry and parameters.  Planar motion is about z, so only izz is emitted.
"""

import numpy as np

from .robotgeometry import FiveBarGeometry
from .dynamics import DynamicParameters


def _g(x):
    """Format a float compactly but losslessly for URDF output."""
    return "%.10g" % float(x)


def _link(name, mass, com_x, izz):
    """One <link> with an <inertial> block (com on the local x axis)."""
    return (
        '  <link name="%s">\n'
        '    <inertial><origin xyz="%s 0 0"/><mass value="%s"/>\n'
        '      <inertia ixx="0" ixy="0" ixz="0" iyy="0" iyz="0" izz="%s"/></inertial>\n'
        '  </link>\n' % (name, _g(com_x), _g(mass), _g(izz)))


def _revolute(name, parent, child, x):
    return (
        '  <joint name="%s" type="continuous">\n'
        '    <parent link="%s"/><child link="%s"/>\n'
        '    <origin xyz="%s 0 0"/><axis xyz="0 0 1"/>\n'
        '  </joint>\n' % (name, parent, child, _g(x)))


def _fixed(name, parent, child, x):
    return (
        '  <joint name="%s" type="fixed">\n'
        '    <parent link="%s"/><child link="%s"/>\n'
        '    <origin xyz="%s 0 0"/>\n'
        '  </joint>\n' % (name, parent, child, _g(x)))


def build_urdf_string(geom, params, name="fivebar_pantograph"):
    """Return the URDF XML (as a string) for the given geometry and inertial
    parameters.  The apex/payload mass is split equally over the two tip links
    (they are the same physical point; the loader sums them)."""
    half_apex = 0.5 * params.apex_mass
    out = ['<?xml version="1.0"?>\n',
           '<!-- Generated by polypantograph urdf_builder.py. Spanning-tree\n'
           '     form: two 2R legs off a base, each ending in a fixed apex tip;\n'
           '     the five-bar loop closure is supplied by the model. Planar\n'
           '     motion about z (izz only). Lengths in m, mass in kg. -->\n',
           '<robot name="%s">\n' % name,
           '  <link name="base"/>\n']
    for i, sign in ((0, -1.0), (1, +1.0)):
        leg = i + 1
        out.append('\n  <!-- leg %d (motor at x = %s d/2) -->\n'
                   % (leg, "-" if sign < 0 else "+"))
        out.append(_revolute("motor%d" % leg, "base", "proximal%d" % leg,
                             sign * geom.d / 2.0))
        out.append(_link("proximal%d" % leg, params.proximal_mass[i],
                         params.proximal_com[i], params.proximal_inertia[i]))
        out.append(_revolute("elbow%d" % leg, "proximal%d" % leg,
                             "distal%d" % leg, geom.proximal[i]))
        out.append(_link("distal%d" % leg, params.distal_mass[i],
                         params.distal_com[i], params.distal_inertia[i]))
        out.append(_fixed("tip%d" % leg, "distal%d" % leg, "apex%d" % leg,
                         geom.distal[i]))
        out.append(_link("apex%d" % leg, half_apex, 0.0, 0.0))
    out.append('</robot>\n')
    return "".join(out)


def write_urdf(path, geom, params, name="fivebar_pantograph"):
    """Write the URDF to path and return the path."""
    with open(path, "w") as f:
        f.write(build_urdf_string(geom, params, name))
    return path


def write_urdf_symmetric(path, name, a, b, d,
                         proximal_mass, distal_mass, apex_mass=0.0):
    """Convenience: build a symmetric, uniform-rod robot from scalars and write
    its URDF.  Returns the path."""
    geom = FiveBarGeometry.symmetric(a, b, d)
    params = DynamicParameters.uniform(geom, proximal_mass, distal_mass,
                                       apex_mass)
    return write_urdf(path, geom, params, name)

if __name__ == "__main__":
    # demo: write the reference robot to a URDF file.
    # usage: python urdf_builder.py [output_path] [robot_name]
    import sys
    out_path = sys.argv[1] if len(sys.argv) > 1 else "fivebar_generated.urdf"
    robot_name = sys.argv[2] if len(sys.argv) > 2 else "fivebar_pantograph"
    geom = FiveBarGeometry.symmetric(0.20, 0.25, 0.20)
    par = DynamicParameters.uniform(geom, 0.5, 0.3, apex_mass=0.10)
    write_urdf(out_path, geom, par, name=robot_name)
    print("wrote URDF to %s (robot name: %s)" % (out_path, robot_name))
